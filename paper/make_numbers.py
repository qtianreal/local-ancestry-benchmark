"""Emit LaTeX macros from the experiment JSONs.

Every number quoted in the manuscript is defined here and nowhere else, so the
prose cannot drift from the results it describes. Any macro the manuscript
references but that no experiment provides is emitted as a visible
placeholder, and listed on stderr, so a missing result is loud rather than a
silent compile failure.
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "results"
OUT = HERE / "numbers.tex"
TEX = HERE / "manuscript.tex"

PAIR_RE = re.compile(r"^real_[A-Z]{3}_[A-Z]{3}\.json$")

WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven",
         "eight", "nine", "ten", "eleven"]


def load(name):
    p = RES / name
    return json.loads(p.read_text()) if p.exists() else None


def fmt(x, dp=3):
    return f"{x:.{dp}f}"


def main():
    lines = ["% Auto-generated by make_numbers.py -- do not edit by hand.", ""]
    defined = {}

    def add(name, value):
        defined[name] = str(value)

    # --- main sweep: prefer the seed-aggregated file -------------------------
    agg = load("aggregate_results.json")
    rows = agg or load("main_results.json") or []
    rows = sorted(rows, key=lambda r: r["fst"])

    if rows:
        add("NDivergence", len(rows))
        add("NSeeds", rows[0].get("n_seeds", 1))
        # The floor is quoted from the run that includes the released tools,
        # whose Fst estimates come from different replicates of the same split
        # times. Reporting the range from the main sweep alone would place the
        # floor outside the stated span, so take the extremes over both.
        _ext = load("external_aggregate.json") or []
        _all = [r["fst"] for r in rows] + [r["fst"] for r in _ext]
        add("FstMin", fmt(min(_all), 4))
        add("FstMax", fmt(max(_all), 3))
        add("TrainEx", rows[0].get("train_examples", "3840"))
        add("TestEx", rows[0].get("test_examples", "512"))
        for i, r in enumerate(rows[: len(WORDS)]):
            tag = f"L{WORDS[i]}"
            add(f"fst{tag}", fmt(r["fst"], 4))
            for m in ("naive_bayes", "hmm", "cnn"):
                short = {"naive_bayes": "nb", "hmm": "hmm", "cnn": "cnn"}[m]
                add(f"{short}{tag}", fmt(r[m]))
                add(f"{short}sd{tag}", fmt(r.get(f"{m}_sd", 0.0)))
        gaps = [r["cnn"] - r["hmm"] for r in rows]
        k = max(range(len(gaps)), key=lambda i: gaps[i])
        add("gainPeak", fmt(gaps[k]))
        add("fstPeak", fmt(rows[k]["fst"], 4))
        add("gainLo", fmt(gaps[0]))
        add("gainHi", fmt(gaps[-1]))
        add("hmmDrop", fmt(rows[-1]["hmm"] - rows[0]["hmm"]))
        add("cnnDrop", fmt(rows[-1]["cnn"] - rows[0]["cnn"]))
        near = min(rows, key=lambda r: abs(r["fst"] - 0.006))
        add("chbFst", fmt(near["fst"], 4))
        for m, short in (("naive_bayes", "NB"), ("hmm", "HMM"), ("cnn", "CNN")):
            add(f"chb{short}", fmt(near[m]))

    # --- transfer matrix ----------------------------------------------------
    tr = load("transfer_results.json")
    if tr:
        m, n = tr["matrix"], len(tr["matrix"])
        diag = [m[i][i] for i in range(n)]
        row_means = [sum(m[i]) / n for i in range(n)]
        best = max(range(n), key=lambda i: row_means[i])
        add("transferDiagMean", fmt(sum(diag) / n))
        add("oracleGap", fmt(sum(diag) / n - row_means[best]))
        add("bestSingleFst", fmt(tr["fst"][best], 4))
        add("bestSingleMean", fmt(row_means[best]))
        worst, desc = 0.0, ""
        for i in range(n):
            for j in range(n):
                if i != j and m[j][j] - m[i][j] > worst:
                    worst = m[j][j] - m[i][j]
                    desc = (rf"trained at $F_{{ST}}={tr['fst'][i]:.4f}$, "
                            rf"evaluated at $F_{{ST}}={tr['fst'][j]:.4f}$")
        add("transferWorstDrop", fmt(worst))
        add("transferWorstDesc", desc)

    # --- pruning ------------------------------------------------------------
    pr = load("pruning_summary.json")
    if pr:
        pr = sorted(pr, key=lambda r: r["fst"])
        k = min(range(len(pr)), key=lambda i: pr[i]["retention"])
        add("retentionMin", fmt(pr[k]["retention"]))
        add("retentionMinFst", fmt(pr[k]["fst"], 4))
        add("retentionLo", fmt(pr[0]["retention"]))
        add("retentionLoSD", fmt(pr[0].get("retention_sd", 0.0)))
        add("retentionMinSD", fmt(pr[k].get("retention_sd", 0.0)))
        add("retentionHiSD", fmt(pr[-1].get("retention_sd", 0.0)))
        add("retentionHi", fmt(pr[-1]["retention"]))

    # --- external tools -----------------------------------------------------
    ex = load("external_aggregate.json") or load("external_results.json")
    if ex:
        ex = sorted(ex, key=lambda r: r["fst"])
        add("NExternal", len(ex))
        for i, r in enumerate(ex[: len(WORDS)]):
            tag = f"X{WORDS[i]}"
            add(f"fst{tag}", fmt(r["fst"], 4))
            for key, short in (("rfmix", "rfmix"), ("flare", "flare"), ("cnn", "excnn")):
                v = r.get(key)
                add(f"{short}{tag}", fmt(v) if isinstance(v, float) else "n/a")

    # --- feasibility threshold and external peak ----------------------------
    if ex:
        def best_ext(r):
            vs = [r.get(k) for k in ("rfmix", "flare")]
            vs = [v for v in vs if isinstance(v, float)]
            return max(vs) if vs else None

        # Use the *paired* gap -- computed per replicate then averaged -- not the
        # difference of the averaged accuracies. They differ because which of
        # RFMix and FLARE is better varies by replicate, so the mean of the
        # per-replicate maxima exceeds the maximum of the means. The paired
        # figure is the conservative one and is what the reported spread and t
        # statistic describe.
        gaps = []
        for r in ex:
            b = best_ext(r)
            if b is not None and "gap" in r:
                gaps.append((r["gap"], r["fst"], b, r["cnn"]))
        if gaps:
            g, f, b, c = max(gaps)
            add("extPeakGain", fmt(g))
            add("extPeakFst", fmt(f, 4))
            add("extPeakBest", fmt(b))
            add("extPeakCNN", fmt(c))
            add("extLoGain", fmt(gaps[0][0]))
            add("extHiGain", fmt(gaps[-1][0]))
            peak = max(ex, key=lambda r: r.get("gap", -9))
            if "gap" in peak:
                add("extPeakGainSD", fmt(peak.get("gap_sd", 0.0)))
                add("extPeakT", f"{peak.get('gap_t', float('nan')):.1f}")
            add("extNSeeds", ex[0].get("n_seeds", 1))
            lo = [r for r in ex if r["fst"] < 0.015 and "gap_vals" in r]
            vals = [v for r in lo for v in r["gap_vals"]]
            if vals:
                import statistics as _st
                add("extLoMean", fmt(sum(vals) / len(vals)))
                add("extLoSD", fmt(_st.pstdev(vals) if len(vals) > 1 else 0.0))
                add("extLoPos", sum(1 for v in vals if v > 0))
                add("extLoN", len(vals))

        # Highest divergence at which no method exceeds 0.60 -- the point below
        # which local ancestry inference carries essentially no information.
        floor = None
        for r in sorted(ex, key=lambda r: r["fst"]):
            vals = [r[k] for k in ("naive_bayes", "hmm", "cnn") if isinstance(r.get(k), float)]
            b = best_ext(r)
            if b is not None:
                vals.append(b)
            if max(vals) < 0.60:
                floor = r
        if floor is not None:
            add("floorFst", fmt(floor["fst"], 4))
            add("floorBest", fmt(max(
                [floor[k] for k in ("naive_bayes", "hmm", "cnn")] + [best_ext(floor)])))

    # --- real data ----------------------------------------------------------
    real = load("real_CHB_CHS.json")
    if real:
        add("realFst", fmt(real["fst"], 5))
        add("realNB", fmt(real["naive_bayes"]))
        add("realHMM", fmt(real["hmm"]))
        add("realCNN", fmt(real["cnn"]))
        add("realSites", real["n_sites"])

    # --- real pairs, including released tools --------------------------------
    import glob
    reals = []
    for f in sorted(glob.glob(str(RES / "real_*.json"))):
        if not PAIR_RE.match(Path(f).name):
            continue  # tuning/ablation output, not a population pair
        r = json.loads(Path(f).read_text())
        tag = "_".join(r["pops"])
        ep = RES / f"realext_{tag}.json"
        if ep.exists():
            r.update({k: v for k, v in json.loads(ep.read_text()).items()
                      if k in ("rfmix", "flare")})
        reals.append(r)
    reals.sort(key=lambda r: r["fst"])
    if reals:
        add("NRealPairs", len(reals))
        add("realFstMin", fmt(reals[0]["fst"], 5))
        add("realFstMax", fmt(reals[-1]["fst"], 5))
        keys = ("naive_bayes", "hmm", "rfmix", "flare", "cnn")
        short = {"naive_bayes": "NB", "hmm": "HMM", "rfmix": "RF",
                 "flare": "FL", "cnn": "CNN"}
        for i, r in enumerate(reals[: len(WORDS)]):
            tag = f"R{WORDS[i]}"
            add(f"pair{tag}", "/".join(r["pops"]))
            add(f"fst{tag}", fmt(r["fst"], 5))
            for k in keys:
                v = r.get(k)
                add(f"{short[k]}{tag}", fmt(v) if isinstance(v, float) else "n/a")
        # Haplotype-aware accuracy per pair, matched by population tag. These
        # are 5-seed means from the input-parity experiment; the CNN column
        # beside them is the single run reported in the original sweep, and the
        # caption says so.
        ipr = {tuple(r["pops"]): r for r in (load("inputs_summary.json") or [])}
        for i, r in enumerate(reals[: len(WORDS)]):
            k = tuple(r["pops"])
            add(f"CNNH R{WORDS[i]}".replace(" ", ""),
                fmt(ipr[k]["acc"]["haplo"]) if k in ipr else "n/a")

        # How often the learned network is beaten by a released tool.
        beaten = sum(
            1 for r in reals
            if isinstance(r.get("cnn"), float) and max(
                [v for v in (r.get("rfmix"), r.get("flare")) if isinstance(v, float)] or [-1]
            ) > r["cnn"])
        add("realCNNBeaten", beaten)
        add("realCNNTotal", len(reals))
        # Largest real-data deficit of the network against the best tool.
        worst = max(
            (max([v for v in (r.get("rfmix"), r.get("flare")) if isinstance(v, float)] or [0])
             - r["cnn"], "/".join(r["pops"]))
            for r in reals if isinstance(r.get("cnn"), float))
        add("realWorstDeficit", fmt(worst[0]))
        add("realWorstPair", worst[1])

        # Spread of the deficit, and whether divergence explains it.
        gaps, fsts = [], []
        for r in reals:
            ext = [v for v in (r.get("rfmix"), r.get("flare")) if isinstance(v, float)]
            if ext and isinstance(r.get("cnn"), float):
                gaps.append(r["cnn"] - max(ext)); fsts.append(r["fst"])
        if gaps:
            add("realGapMean", f"{sum(gaps)/len(gaps):+.3f}")
            add("realGapMin", f"{min(gaps):+.3f}")
            add("realGapMax", f"{max(gaps):+.3f}")
            add("realCNNWins", sum(1 for g in gaps if g > 0))
            try:
                from scipy.stats import spearmanr
                rho, pv = spearmanr(fsts, gaps)
                add("realSpearman", f"{rho:+.2f}")
                add("realSpearmanP", f"{pv:.2f}")
            except Exception:
                pass
            # Widest deficit spread between two pairs of similar divergence.
            best = (0.0, "", "")
            for i in range(len(reals)):
                for j in range(i + 1, len(reals)):
                    if abs(fsts[i] - fsts[j]) / max(fsts[i], fsts[j]) < 0.05:
                        d = abs(gaps[i] - gaps[j])
                        if d > best[0]:
                            best = (d, "/".join(reals[i]["pops"]), "/".join(reals[j]["pops"]))
            if best[1]:
                add("realMatchedSpread", fmt(best[0]))
                add("realMatchedA", best[1]); add("realMatchedB", best[2])

    # --- tract-level structure ----------------------------------------------
    tr_rows = load("tract_results.json")
    if tr_rows:
        import math
        short = {"naive_bayes": "NB", "hmm": "HMM", "rfmix": "RF",
                 "flare": "FL", "cnn": "CNN"}
        for m, s in short.items():
            n = [r[m]["n_tract_ratio"] for r in tr_rows
                 if m in r and not math.isnan(r[m]["n_tract_ratio"])]
            l = [r[m]["length_ratio"] for r in tr_rows
                 if m in r and not math.isnan(r[m]["length_ratio"])]
            if n:
                add(f"tractN{s}", fmt(sum(n) / len(n), 1))
                add(f"tractLen{s}", fmt(sum(l) / len(l), 2))
        # The haplotype-aware configuration exists at a subset of levels, so
        # its mean is reported alongside the frequency-only mean restricted to
        # the same levels. Averaging over different level sets would make the
        # two rows silently incomparable.
        hap_lv = [r["split_time"] for r in tr_rows if "cnn_haplo" in r]
        if hap_lv:
            sub = [r for r in tr_rows if r["split_time"] in hap_lv]
            add("tractHapLevels", len(hap_lv))
            add("tractNCNNhap", fmt(sum(r["cnn_haplo"]["n_tract_ratio"]
                                        for r in sub) / len(sub), 1))
            add("tractLenCNNhap", fmt(sum(r["cnn_haplo"]["length_ratio"]
                                          for r in sub) / len(sub), 2))
            add("tractNCNNmatched", fmt(sum(r["cnn"]["n_tract_ratio"]
                                            for r in sub) / len(sub), 1))
        cnn_worst = max(r["cnn"]["n_tract_ratio"] for r in tr_rows if "cnn" in r)
        add("tractNCNNworst", fmt(cnn_worst, 0))
        add("tractNlevels", len(tr_rows))

    # --- implied admixture dates --------------------------------------------
    dt = load("dating_results.json")
    if dt:
        import math
        short = {"truth": "Truth", "naive_bayes": "NB", "hmm": "HMM",
                 "rfmix": "RF", "flare": "FL", "cnn": "CNN"}
        means = {}
        for m, s in short.items():
            v = [r[m] for r in dt if m in r and math.isfinite(r[m])]
            if v:
                means[m] = sum(v) / len(v)
                add(f"date{s}", fmt(means[m], 0))
        if "truth" in means:
            for m, s in short.items():
                if m in means and m != "truth":
                    add(f"dateRatio{s}", fmt(means[m] / means["truth"], 1))
        add("dateTrueG", 30)
        add("dateNlevels", len(dt))

    # --- Viterbi decoding of the network's logits ---------------------------
    crf = load("crf_results.json")
    if crf:
        import math
        # These macros describe the frequency-only network. The file now also
        # holds the haplotype-aware arm, and averaging the two together silently
        # moved the published tract ratio from 1.56 to 1.64.
        crf = [r for r in crf if r.get("config", "freq") == "freq"]
        mean = lambda k: sum(r[k] for r in crf if math.isfinite(r[k])) / \
                         sum(1 for r in crf if math.isfinite(r[k]))
        add("crfAccRaw", fmt(mean("raw_acc")))
        add("crfAccVit", fmt(mean("crf_acc")))
        # Signed: the change is small but positive, and "changing accuracy by
        # 0.0002" left readers to guess whether the fix cost anything.
        _d = mean("crf_acc") - mean("raw_acc")
        add("crfAccDelta", f"{_d:+.4f}")
        add("crfAccBetter", sum(1 for r in crf if r["crf_acc"] > r["raw_acc"]))
        add("crfAccN", len(crf))
        add("crfNRaw", fmt(mean("raw_ntract"), 1))
        add("crfNVit", fmt(mean("crf_ntract"), 2))
        add("crfLenVit", fmt(mean("crf_len"), 2))
        add("crfGRaw", fmt(mean("raw_g"), 0))
        add("crfGVit", fmt(mean("crf_g"), 0))
        add("crfGTruth", fmt(mean("true_g"), 0))
        add("crfNlevels", len({r["split_time"] for r in crf}))
        add("crfNseeds", len({r["seed"] for r in crf}))

    # --- phasing error ------------------------------------------------------
    ph = load("phasing_results.json")
    if ph:
        short = {"naive_bayes": "NB", "hmm": "HMM", "rfmix": "RF",
                 "flare": "FL", "cnn": "CNN", "cnn_haplo": "CNNH"}
        levels = sorted({r["split_time"] for r in ph})
        tags = ["Lo", "Hi"]
        for T, tag in zip(levels, tags):
            cells = {r["switch_per_mb"]: r for r in ph if r["split_time"] == T}
            rates = sorted(cells)
            add(f"phaseFst{tag}", fmt(cells[rates[0]]["fst"], 4))
            add(f"phaseMaxRate{tag}", fmt(rates[-1], 1))
            for m, s in short.items():
                for r in rates:
                    key = "Zero" if r == 0 else ("Half" if r < 1 else "Two")
                    add(f"phase{s}{key}{tag}", fmt(cells[r][m]))
                if m in cells[rates[0]] and m in cells[rates[-1]]:
                    add(f"phase{s}Drop{tag}",
                        fmt(cells[rates[-1]][m] - cells[rates[0]][m]))
            # rate at which a released tool first overtakes the network
            flip = next((r for r in rates
                         if max(cells[r]["rfmix"], cells[r]["flare"]) > cells[r]["cnn"]), None)
            add(f"phaseFlip{tag}", fmt(flip, 1) if flip is not None else "none")
            if "cnn_haplo" in cells[rates[0]]:
                fh = next((r for r in rates
                           if max(cells[r]["rfmix"], cells[r]["flare"])
                           > cells[r]["cnn_haplo"]), None)
                add(f"phaseFlipH{tag}", fmt(fh, 1) if fh is not None else "none")
                add(f"phaseHapGain{tag}",
                    fmt(cells[rates[-1]]["cnn_haplo"] - cells[rates[-1]]["cnn"]))

    # --- channel ablation ---------------------------------------------------
    hp = load("haplo_results.json")
    if hp:
        hp = sorted(hp, key=lambda r: r["fst"])
        k = max(range(len(hp)), key=lambda i: hp[i]["delta"])
        add("haploBestDelta", fmt(hp[k]["delta"]))
        add("haploBestFst", fmt(hp[k]["fst"], 4))
        add("haploMeanDelta", f"{sum(r['delta'] for r in hp) / len(hp):+.3f}")

    # --- normalisation ablation (results/tuning/, quarantined from the sweep) -
    norm = load("tuning/norm_CHB_CDX.json")
    if norm:
        import statistics as st
        base = {r["seed"]: r["acc"] for r in norm if r["config"] == "groupnorm"}
        bn = [r for r in norm if r["config"] == "batchnorm"]
        d = [r["acc"] - base[r["seed"]] for r in bn if r["seed"] in base]
        gn_disc = max(abs(r["discrepancy"]) for r in norm
                      if r["config"] == "groupnorm")
        add("normSeeds", len(d))
        add("normDelta", f"{st.mean(d):+.3f}")
        add("normDeltaAbs", fmt(abs(st.mean(d))))
        add("normDeltaSD", fmt(st.stdev(d)))
        add("normWorseCount", sum(1 for x in d if x < 0))
        add("normBNDisc", fmt(st.mean(abs(r["discrepancy"]) for r in bn)))
        add("normBNDiscMax", fmt(max(abs(r["discrepancy"]) for r in bn)))
        add("normGNDisc", fmt(gn_disc))

    # --- inter-site spacing: sizes the positional-information asymmetry ------
    sp = load("spacing.json")
    if sp:
        add("spacingCVsim", f"{sp['simulated']['cv']:.2f}")
        add("spacingCVreal", f"{sp['real']['cv']:.2f}")
        add("spacingTailSim", f"{sp['simulated']['p99_over_p50']:.1f}")
        add("spacingTailReal", f"{sp['real']['p99_over_p50']:.1f}")

    # --- input parity: haplotype features on real pairs -----------------------
    ip = load("inputs_summary.json")
    if ip:
        import statistics as st
        CUT = 0.04
        lo = [r for r in ip if r["fst"] < CUT]
        hi = [r for r in ip if r["fst"] >= CUT]
        dl = [r["acc"]["delta"] for r in lo]
        dh = [r["acc"]["delta"] for r in hi]
        add("ipPairs", len(ip))
        add("ipCut", f"{CUT:g}")
        add("ipLoN", len(lo))
        add("ipHiN", len(hi))
        add("ipLoGain", f"{st.mean(dl):+.3f}")
        add("ipLoGainAbs", fmt(abs(st.mean(dl))))
        add("ipLoPos", sum(1 for x in dl if x > 0))
        add("ipHiGain", f"{st.mean(dh):+.3f}")
        add("ipHiGainAbs", fmt(abs(st.mean(dh))))
        add("ipHiPos", sum(1 for x in dh if x > 0))
        best = max(ip, key=lambda r: r["acc"]["delta"])
        add("ipBestGain", f"{best['acc']['delta']:+.3f}")
        add("ipBestPair", "/".join(best["pops"]))
        add("ipBestFst", fmt(best["fst"], 4))
        add("ipBeatsRfmix", sum(1 for r in ip if r.get("rfmix")
                                and r["acc"]["haplo"] > r["rfmix"]))
        add("ipBeatsRfmixFreq", sum(1 for r in ip if r.get("rfmix")
                                    and r["acc"]["freq"] > r["rfmix"]))
        add("ipBeatsFlare", sum(1 for r in ip if r.get("flare")
                                and r["acc"]["haplo"] > r["flare"]))
        add("ipBeatsFlareFreq", sum(1 for r in ip if r.get("flare")
                                    and r["acc"]["freq"] > r["flare"]))
        for nm, key in (("Rfmix", "rfmix"), ("Flare", "flare")):
            add(f"ipLoBeats{nm}", sum(1 for r in lo if r.get(key)
                                      and r["acc"]["haplo"] > r[key]))
            add(f"ipLoBeats{nm}Freq", sum(1 for r in lo if r.get(key)
                                          and r["acc"]["freq"] > r[key]))
        # The in-range exception, and its nearest neighbour in divergence.
        worst = min(lo, key=lambda r: r["acc"]["delta"])
        add("ipExceptionPair", "/".join(worst["pops"]))
        add("ipExceptionAbs", fmt(abs(worst["acc"]["delta"])))
        near = min((r for r in lo if r is not worst),
                   key=lambda r: abs(r["fst"] - worst["fst"]))
        add("ipBestGainNeighbour", f"{near['acc']['delta']:+.3f}")
        tr = [r["tracts"]["delta"] for r in ip]
        add("ipTractImproved", sum(1 for x in tr if x < 0))
        add("ipTractLo", f"{st.mean([r['tracts']['delta'] for r in lo]):+.1f}")

    # --- haplotype-sharing comparison, simulated vs real ----------------------
    sh = load("sharing.json")
    if sh:
        import numpy as _np
        sim = sorted([r for r in sh if r["source"] == "simulated"],
                     key=lambda r: r["fst"])
        real = sorted([r for r in sh if r["source"] == "real"],
                      key=lambda r: r["fst"])
        sf = [r["fst"] for r in sim]
        sa = [r["match_accuracy"] for r in sim]
        # Interpolate the simulated curve to each real pair's divergence, so the
        # comparison uses every point rather than a hand-picked matched pair.
        diffs = [r["match_accuracy"] - float(_np.interp(r["fst"], sf, sa))
                 for r in real if sf[0] <= r["fst"] <= sf[-1]]
        add("sharingN", len(diffs))
        add("sharingSimHigher", sum(1 for d in diffs if d < 0))
        add("sharingMeanDiff", fmt(abs(sum(diffs) / len(diffs))))

    # --- powered simulation replication of the haplotype ablation -------------
    hs = load("tuning/inputs_sim.json")
    if hs:
        import statistics as st
        levels = sorted({r["split_time"] for r in hs})
        per = []
        for T in levels:
            b = {r["seed"]: r["acc"] for r in hs
                 if r["split_time"] == T and r["features"] == "freq"}
